CREATE TABLE IF NOT EXISTS gateway_keys (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  key_id VARCHAR(96) NOT NULL,
  key_prefix VARCHAR(128) NOT NULL,
  token_hash CHAR(64) NOT NULL,
  key_type VARCHAR(32) NOT NULL,
  name VARCHAR(160) NOT NULL,
  description TEXT NULL,
  owner_user_id INT NULL,
  instance_id INT NULL,
  allowed_model_groups JSON NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'active',
  expires_at TIMESTAMP NULL,
  last_used_at TIMESTAMP NULL,
  created_by_user_id INT NULL,
  revoked_at TIMESTAMP NULL,
  revoked_by_user_id INT NULL,
  revocation_reason VARCHAR(255) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uk_gateway_keys_key_id (key_id),
  UNIQUE KEY uk_gateway_keys_token_hash (token_hash),
  UNIQUE KEY uk_gateway_keys_managed_instance (instance_id, key_type),
  KEY idx_gateway_keys_owner_status (owner_user_id, status),
  KEY idx_gateway_keys_expires_at (expires_at),
  CONSTRAINT fk_gateway_keys_instance FOREIGN KEY (instance_id) REFERENCES instances(id) ON DELETE CASCADE,
  CONSTRAINT fk_gateway_keys_owner FOREIGN KEY (owner_user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
