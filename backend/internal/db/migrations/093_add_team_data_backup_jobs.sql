CREATE TABLE IF NOT EXISTS system_team_data_backup_jobs (
  public_id VARCHAR(36) PRIMARY KEY,
  operation VARCHAR(16) NOT NULL,
  source_backup_id VARCHAR(36) NULL,
  actor_id INT NOT NULL,
  idempotency_key VARCHAR(128) NOT NULL,
  request_hash CHAR(64) NOT NULL,
  config_hash CHAR(64) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'pending',
  phase VARCHAR(40) NOT NULL DEFAULT 'queued',
  error_code VARCHAR(64) NOT NULL DEFAULT '',
  cancel_requested BOOLEAN NOT NULL DEFAULT FALSE,
  owner_id VARCHAR(80) NULL,
  report_json JSON NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  started_at DATETIME(6) NULL,
  finished_at DATETIME(6) NULL,
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  active_slot TINYINT GENERATED ALWAYS AS (CASE WHEN status IN ('pending','running','canceling') THEN 1 ELSE NULL END) STORED,
  UNIQUE KEY uk_team_data_backup_idempotency (actor_id,idempotency_key),
  UNIQUE KEY uk_team_data_backup_active (active_slot),
  KEY idx_team_data_backup_created (created_at),
  CONSTRAINT chk_team_data_backup_operation CHECK (operation IN ('backup','restore','cleanup')),
  CONSTRAINT chk_team_data_backup_status CHECK (status IN ('pending','running','canceling','succeeded','failed','canceled','cleaned'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
