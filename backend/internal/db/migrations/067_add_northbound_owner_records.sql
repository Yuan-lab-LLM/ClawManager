-- Owner dashboard facts, aggregates and future growth/task records.
-- No foreign keys: instance/account deletion must not erase historical usage.
-- Gateway never queries this table; only the existing Core account writes it.
-- Empty metrics remain NULL when unavailable rather than claiming measured zero.
CREATE TABLE IF NOT EXISTS northbound_owner_records (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  record_type VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  record_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  scope_id BIGINT UNSIGNED NOT NULL,
  owner VARCHAR(128) NULL,
  owner_normalized VARCHAR(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
  instance_id BIGINT UNSIGNED NULL,
  runtime_type VARCHAR(32) NULL,
  instance_mode VARCHAR(16) NULL,
  source_kind VARCHAR(32) NULL,
  source_key VARCHAR(255) NULL,
  session_key VARCHAR(255) NULL,
  question_key VARCHAR(255) NULL,
  status VARCHAR(24) NOT NULL,
  occurred_at DATETIME(6) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  version BIGINT UNSIGNED NOT NULL DEFAULT 0,
  schema_version SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  rule_version VARCHAR(64) NULL,
  payload JSON NULL,
  prompt_tokens BIGINT UNSIGNED NULL,
  completion_tokens BIGINT UNSIGNED NULL,
  total_tokens BIGINT UNSIGNED NULL,
  invocation_count BIGINT UNSIGNED NULL,
  question_count BIGINT UNSIGNED NULL,
  session_count BIGINT UNSIGNED NULL,
  active_day_count INT UNSIGNED NULL,
  xp_value BIGINT NULL,
  level_value INT UNSIGNED NULL,
  streak_days INT UNSIGNED NULL,
  longest_streak_days INT UNSIGNED NULL,
  rank_position BIGINT UNSIGNED NULL,
  rank_score DECIMAL(24,6) NULL,
  last_activity_at DATETIME(6) NULL,
  business_date DATE NULL,
  timezone VARCHAR(64) NOT NULL DEFAULT 'Asia/Shanghai',
  period_type VARCHAR(16) NULL,
  period_start DATE NULL,
  period_end DATE NULL,
  category_key VARCHAR(64) NULL,
  revision INT UNSIGNED NOT NULL DEFAULT 1,
  expires_at DATETIME(6) NULL,
  active_work_seconds BIGINT UNSIGNED NULL,
  login_day_count INT UNSIGNED NULL,
  login_streak_days INT UNSIGNED NULL,
  last_login_date DATE NULL,
  task_completed_count BIGINT UNSIGNED NULL,
  interval_start DATETIME(6) NULL,
  interval_end DATETIME(6) NULL,
  task_code VARCHAR(64) NULL,
  definition_version VARCHAR(64) NULL,
  progress_value BIGINT UNSIGNED NULL,
  target_value BIGINT UNSIGNED NULL,
  completed_at DATETIME(6) NULL,
  rewarded_at DATETIME(6) NULL,
  UNIQUE KEY uk_owner_record (record_type, record_key),
  KEY idx_owner_record_time (scope_id, owner_normalized, record_type, occurred_at),
  KEY idx_owner_record_day (scope_id, owner_normalized, record_type, business_date),
  KEY idx_owner_record_rank (scope_id, record_type, category_key, period_start, rank_position),
  KEY idx_owner_record_instance (scope_id, owner_normalized, instance_id, record_type, occurred_at),
  KEY idx_owner_record_pending (record_type, status, id),
  KEY idx_owner_record_source (record_type, source_kind, source_key),
  KEY idx_owner_record_binding (record_type, instance_id),
  KEY idx_owner_record_portal (owner_normalized, record_type, occurred_at, scope_id),
  KEY idx_owner_record_task (scope_id, owner_normalized, record_type, task_code, period_start),
  KEY idx_owner_record_interval (scope_id, owner_normalized, record_type, interval_start, interval_end)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
