// DataJobRequest operates only on an already isolated, owned target. Resource
// provisioning, network policy and writer revocation are controller duties;
// a successful Job alone is deliberately insufficient for formal acceptance.
type DataJobRequest struct {
	VerifyJobRequest
	Binding            DataOperationBinding `json:"binding"`
	OperationSecret    string               `json:"operation_secret"`
	OperationSecretUID string               `json:"operation_secret_uid"`
	Target             PVCIdentity          `json:"target"`
	NodeName           string               `json:"node_name,omitempty"`
}
type DataJobResult struct {
	State  string                `json:"state"`
	JobUID string                `json:"job_uid"`
	Report *DataOperationReceipt `json:"report,omitempty"`
}
type DataJobs struct{ Client kubernetes.Interface }

func dataJob(a Attempt) (*batchv1.Job, DataJobRequest, error) {
	var r DataJobRequest
	if strictDecode(a.Request, &r) != nil {
		return nil, r, errors.New("validation_failed")
	}
	// The durable attempt row supplies this identity after PrepareAttempt
	// freezes its input. It is never generated by a replacement controller.
	if r.Binding.AttemptID == "" {
		r.Binding.AttemptID = a.ID
	}
	if r.VerifyJobRequest.Validate() != nil || r.Binding.Validate() != nil || r.DeadlineAt.IsZero() || r.ValidateSnapshot || r.MaxItems < 1 || r.MaxItems > 100000000 || r.BootstrapUID == "" || r.Binding.RunID != a.TaskID || r.Binding.AttemptID != a.ID || r.Binding.TargetUID != r.Target.UID || r.Binding.BackupID != r.BackupID || r.Binding.Origin != r.Origin || r.OperationSecret == r.BootstrapSecret || r.OperationSecret == "" || len(validation.IsDNS1123Subdomain(r.OperationSecret)) != 0 || len(validation.IsDNS1123Subdomain(r.Target.Name)) != 0 || r.Target.Name == "" || !refPattern.MatchString(r.OperationSecretUID) || r.NodeName != "" && len(validation.IsDNS1123Subdomain(r.NodeName)) != 0 || (r.Binding.Operation == "restore" && a.Phase != "restore") || (r.Binding.Operation == "verify-restored" && a.Phase != "verify") {
		return nil, r, errors.New("validation_failed")
	}
	base := a
	base.Request, _ = json.Marshal(r.VerifyJobRequest)
	job, _, err := verifyJob(base)
	if err != nil {
		return nil, r, err
	}
	job.Name = "backup-data-" + a.ID[4:]
	h := sha256.Sum256(a.Request)
	job.Annotations["backup.clawmanager.io/request-sha256"] = hex.EncodeToString(h[:])
	role := "restore"
	readOnly := false
	if r.Binding.Operation == "verify-restored" {
		role = "restored-verifier"
		readOnly = true
	}
	job.Labels["backup.clawmanager.io/role"] = role
	job.Spec.Template.Labels["backup.clawmanager.io/role"] = role
	pod := &job.Spec.Template.Spec
	pod.NodeName = r.NodeName
	no := false
	pod.EnableServiceLinks = &no
	grace := int64(5)
	pod.TerminationGracePeriodSeconds = &grace
	// Restored files retain their original numeric owners and 0600 modes. Do
	// not fsGroup/chown the target from the independent verifier's mount.
	zero := int64(0)
	pod.SecurityContext.RunAsNonRoot = &no
	pod.SecurityContext.RunAsUser = &zero
	pod.SecurityContext.RunAsGroup = &zero
	pod.SecurityContext.FSGroup = nil
	c := &pod.Containers[0]
	c.Name = "data-operation"
	c.SecurityContext.Capabilities.Add = []corev1.Capability{"DAC_OVERRIDE"}
	if !readOnly {
		c.SecurityContext.Capabilities.Add = append(c.SecurityContext.Capabilities.Add, "CHOWN", "FOWNER")
	}
	raw, _ := canonicalJSON(r.Binding)
	c.Args = []string{"--operation", r.Binding.Operation, "--bootstrap", "/run/backup-bootstrap/config.json", "--operation-config", "/run/backup-data-config/config.json", "--origin", r.Origin, "--backup", r.BackupID, "--max-bytes", strconv.FormatInt(r.MaxBytes, 10), "--max-items", strconv.Itoa(r.MaxItems), "--timeout", strconv.FormatInt(r.DeadlineSeconds, 10) + "s", "--deadline-at", r.DeadlineAt.UTC().Format(time.RFC3339Nano), "--data-request", base64.RawURLEncoding.EncodeToString(raw), "--report-file", "/dev/termination-log"}
	mode := int32(0440)
	pod.Volumes = append(pod.Volumes, corev1.Volume{Name: "operation", VolumeSource: corev1.VolumeSource{Secret: &corev1.SecretVolumeSource{SecretName: r.OperationSecret, DefaultMode: &mode}}}, corev1.Volume{Name: "target", VolumeSource: corev1.VolumeSource{PersistentVolumeClaim: &corev1.PersistentVolumeClaimVolumeSource{ClaimName: r.Target.Name, ReadOnly: readOnly}}})
	c.VolumeMounts = append(c.VolumeMounts, corev1.VolumeMount{Name: "operation", MountPath: "/run/backup-data-config", ReadOnly: true}, corev1.VolumeMount{Name: "target", MountPath: "/run/backup-target", ReadOnly: readOnly})
	return job, r, nil
}

func (j DataJobs) Ensure(ctx context.Context, a Attempt, uid string, create bool) (*batchv1.Job, error) {
	want, r, err := dataJob(a)
	if err != nil {
		return nil, err
	}
	if uid == "" && !create {
		return nil, errors.New("coordination_invalid")
	}
	inputs := CaptureJobRequest{VerifyJobRequest: r.VerifyJobRequest, BootstrapUID: r.BootstrapUID, OperationSecret: r.OperationSecret, OperationSecretUID: r.OperationSecretUID, Stage: r.Target}
	if err = (CaptureJobs{Client: j.Client}).inputs(ctx, inputs); err != nil {
		return nil, err
	}
	job, err := j.Client.BatchV1().Jobs(r.Namespace).Get(ctx, want.Name, metav1.GetOptions{})
	if apierrors.IsNotFound(err) && uid == "" && create {
		job, err = j.Client.BatchV1().Jobs(r.Namespace).Create(ctx, want, metav1.CreateOptions{})
		if apierrors.IsAlreadyExists(err) {
			job, err = j.Client.BatchV1().Jobs(r.Namespace).Get(ctx, want.Name, metav1.GetOptions{})
		}
	}
	if err != nil {
		return nil, err
	}
	if !matchesCaptureJob(want, job) || uid != "" && string(job.UID) != uid {
		return nil, errors.New("artifact_conflict")
	}
	return job, nil
}

func (j DataJobs) Observe(ctx context.Context, a Attempt, uid string) (DataJobResult, error) {
	out := DataJobResult{State: "running", JobUID: uid}
	job, err := j.Ensure(ctx, a, uid, false)
	if err != nil {
		return out, err
	}
	_, r, _ := dataJob(a)
	complete := false
	for _, c := range job.Status.Conditions {
		if c.Status == corev1.ConditionTrue {
			if c.Type == batchv1.JobFailed {
				out.State = "failed"
				return out, nil
			}
			complete = complete || c.Type == batchv1.JobComplete
		}
	}
	if !complete {
		return out, nil
	}
	pods, err := j.Client.CoreV1().Pods(r.Namespace).List(ctx, metav1.ListOptions{LabelSelector: "backup.clawmanager.io/attempt=" + a.ID})
	if err != nil {
		return out, err
	}
	count := 0
	for _, p := range pods.Items {
		if !ownedByJob(p, job.UID) {
			continue
		}
		count++
		actual := job.DeepCopy()
		actual.Spec.Template.Spec = *p.Spec.DeepCopy()
		actual.Spec.Template.Labels = p.Labels
		if count > 1 || !matchesCaptureJob(job, actual) || len(p.Status.ContainerStatuses) != 1 {
			return out, errors.New("isolation_invalid")
		}
		c := p.Status.ContainerStatuses[0]
		term := c.State.Terminated
		if c.Name != "data-operation" || term == nil || term.ExitCode != 0 || len(term.Message) > 4096 {
			return out, errors.New("evidence_incomplete")
		}
		var receipt DataOperationReceipt
		if strictDecode([]byte(term.Message), &receipt) != nil || receipt.validateBinding(r.Binding) != nil {
			return out, errors.New("evidence_incomplete")
		}
		// The exact history/key descriptors are persisted by the controller as
		// its next verifier intent, never reloaded from restore-report.json.
		out.Report = &receipt
	}
	if count != 1 {
		return out, errors.New("evidence_incomplete")
	}
	out.State = "succeeded"
	return out, nil
}
func businessTableCount() int {
	n := 0
	for _, p := range Registry() {
		if p.BackupStrategy == "mysql_dump" {
			n++
		}
	}
	return n
}

func (j DataJobs) Stop(ctx context.Context, a Attempt, uid string) (bool, error) {
	want, r, err := dataJob(a)
	if err != nil {
		return false, err
	}
	if uid == "" {
		return false, errors.New("cleanup_unsafe_target")
	}
	if err = (VerifyJobs{Client: j.Client}).namespace(ctx, r.VerifyJobRequest); err != nil {
		return false, err
	}
	job, err := j.Client.BatchV1().Jobs(r.Namespace).Get(ctx, want.Name, metav1.GetOptions{})
	if apierrors.IsNotFound(err) {
		pods, e := j.Client.CoreV1().Pods(r.Namespace).List(ctx, metav1.ListOptions{LabelSelector: "backup.clawmanager.io/attempt=" + a.ID})
		if e != nil {
			return false, e
		}
		for _, p := range pods.Items {
			if ownedByJob(p, types.UID(uid)) {
				return false, nil
			}
		}
		return true, nil
	}
	if err != nil {
		return false, err
	}
	if string(job.UID) != uid || !matchesCaptureJob(want, job) {
		return false, errors.New("cleanup_unsafe_target")
	}
	identity := types.UID(uid)
	policy := metav1.DeletePropagationForeground
	err = j.Client.BatchV1().Jobs(r.Namespace).Delete(ctx, job.Name, metav1.DeleteOptions{Preconditions: &metav1.Preconditions{UID: &identity}, PropagationPolicy: &policy})
	return false, err
}
