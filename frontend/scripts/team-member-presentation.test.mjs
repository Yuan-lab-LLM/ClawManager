import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source = fs.readFileSync(new URL('../src/components/teams/teamMemberPresentation.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText;
const mod = { exports: {} };
new Function('exports', compiled)(mod.exports);
const { memberRuntime, memberSchedule, memberRailState, memberPageSize, memberSummary, memberIsStarting, memberHasRuntimeFault } = mod.exports;
for (const status of ['creating', 'idle', 'busy', 'failed', 'offline', 'deleting', 'deleted']) assert.ok(memberSchedule(status).label);
assert.equal(memberRuntime(undefined).label, '待确认');
assert.equal(memberRuntime('unknown').tone, 'unknown');
assert.equal(memberRuntime('idle').label, '空闲', 'heartbeat does not prove desktop access');
assert.equal(memberRuntime('future-status').label, 'future-status', 'unknown protocol values must not become healthy');
assert.equal(memberRuntime('future-status').tone, 'unknown');
assert.equal(memberRailState({ status: 'idle', availability: 'future-status' }).tone, 'unknown');
assert.equal(memberRailState({ status: 'idle', availability: 'blocked' }).tone, 'error');
assert.equal(memberRailState({ status: 'busy', availability: 'offline' }).tone, 'error');
assert.equal(memberRailState({ status: 'idle', availability: 'unknown' }).label, '待确认');
assert.equal(memberRailState({ status: 'failed', availability: 'idle' }).label, '失败');
assert.equal(memberRailState({ status: 'idle', availability: 'busy' }).label, '运行忙碌');
assert.equal(memberRailState({ status: 'idle', availability: 'idle', blocked_reason: 'fault' }).label, '运行异常');
for(const runtime_status of ['creating','starting','pending']){
  const warming={status:'creating',availability:'unknown',runtime_status};
  assert.equal(memberRailState(warming).label,'启动中');assert.equal(memberRailState(warming).tone,'neutral');
  assert.equal(memberRuntime('unknown',runtime_status).label,'启动中');assert.equal(memberIsStarting(warming),true);
  const legacy={...warming,availability:'offline',blocked_reason:'Runtime unavailable: linked instance is starting'};
  assert.equal(memberRailState(legacy).label,'启动中');assert.equal(memberHasRuntimeFault(legacy),false);
  assert.equal(memberSummary(legacy),'实例启动中，正在确认运行状态。');
  const fault={...warming,blocked_reason:'Required source file missing'};
  assert.equal(memberRailState(fault).label,'运行异常');assert.equal(memberHasRuntimeFault(fault),true);
  assert.equal(memberSummary(fault),fault.blocked_reason);
  assert.equal(memberRailState({...warming,status:'failed'}).label,'失败');
}
assert.equal(memberIsStarting({status:'idle',runtime_status:'future-state'}),false);
assert.equal(memberSummary({ blocked_reason: 'fault', runtime_intent: 'working', last_summary: 'old' }), 'fault');
assert.equal(memberSummary({ runtime_intent: 'working', last_summary: 'old' }), 'working');
assert.equal(memberSummary({ last_summary: 'old' }), 'old');
assert.equal(memberPageSize(564, 3), 3);
assert.equal(memberPageSize(563, 3), 2);
assert.equal(memberPageSize(602, 10), 3);
assert.equal(memberPageSize(438, 10), 2);
assert.equal(memberPageSize(437, 10), 1);
assert.equal(memberPageSize(280, 10), 1);
assert.equal(memberPageSize(0, 0), 1);
console.log('PASS: member state provenance, summaries and non-scrolling pagination');
