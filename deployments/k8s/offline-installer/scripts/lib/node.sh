#!/usr/bin/env bash

set -Eeuo pipefail

stage_packages_on_worker() {
  local target=$1
  [[ -f ${PACKAGE_DIR}/Packages.gz ]] || die "offline apt repository is incomplete: ${PACKAGE_DIR}/Packages.gz"
  log "staging offline deb repository on ${target}"
  node_bash "${target}" "mkdir -p '${REMOTE_ROOT}/packages/${TARGET_ARCH}'"
  tar -C "${PACKAGE_DIR}" -cf - . | {
    local -a options=()
    mapfile -t options < <(ssh_options)
    ssh "${options[@]}" "${SSH_USER}@${target}" \
      "sudo -n tar -C '${REMOTE_ROOT}/packages/${TARGET_ARCH}' -xf -"
  }
}

install_node_packages() {
  local target=$1
  local repo_dir
  if [[ ${target} == local ]]; then
    repo_dir=${PACKAGE_DIR}
  else
    repo_dir=${REMOTE_ROOT}/packages/${TARGET_ARCH}
  fi

  if node_step_marked "${target}" packages_installed \
    && node_capture "${target}" "kubeadm version -o short | grep -Fx '${KUBERNETES_VERSION}' >/dev/null"; then
    log "packages already installed on ${target}"
    return
  fi

  log "installing offline packages on ${target}"
  node_bash "${target}" "
set -Eeuo pipefail
repo_dir='${repo_dir}'
source_list='${OWNER_DIR}/offline-apt.list'
mkdir -p '${OWNER_DIR}' '${STATE_DIR}'
chmod 700 '${OWNER_DIR}' '${STATE_DIR}'
printf 'deb [trusted=yes] file:%s ./\n' \"\${repo_dir}\" >\"\${source_list}\"

systemctl stop unattended-upgrades 2>/dev/null || true
systemctl disable unattended-upgrades 2>/dev/null || true
systemctl disable --now apt-daily.timer apt-daily-upgrade.timer 2>/dev/null || true
dpkg --configure -a

apt_opts=(
  -o \"Dir::Etc::sourcelist=\${source_list}\"
  -o 'Dir::Etc::sourceparts=-'
  -o 'APT::Get::List-Cleanup=0'
  -o 'Acquire::Languages=none'
  -o 'APT::Sandbox::User=root'
)
apt-get \"\${apt_opts[@]}\" update
DEBIAN_FRONTEND=noninteractive apt-get \"\${apt_opts[@]}\" install -y --allow-downgrades \
  containerd.io \
  kubelet='${KUBERNETES_DEB_VERSION}' \
  kubeadm='${KUBERNETES_DEB_VERSION}' \
  kubectl='${KUBERNETES_DEB_VERSION}' \
  conntrack socat ebtables ipset iproute2 iptables \
  open-iscsi nfs-common cryptsetup dmsetup \
  ca-certificates curl gpg openssl openssh-client rsync jq python3-minimal
apt-mark hold kubelet kubeadm kubectl

kubeadm version -o short | grep -Fx '${KUBERNETES_VERSION}'
touch '${STATE_DIR}/packages_installed'
"
}

configure_node_system() {
  local target=$1
  local hostname=$2
  local pause_image
  pause_image="$(image_for_key kubernetes.pause)"

  if node_step_marked "${target}" system_configured \
    && node_capture "${target}" "
systemctl is-active containerd >/dev/null
ctr plugins ls | grep -Eq '^io\.containerd\.grpc\.v1[[:space:]]+cri[[:space:]].*[[:space:]]ok[[:space:]]*$'
"; then
    log "system configuration already applied on ${target}"
    return
  fi

  log "configuring Ubuntu, containerd and Longhorn prerequisites on ${hostname}"
  node_bash "${target}" "
set -Eeuo pipefail
hostnamectl set-hostname '${hostname}'
if grep -qE '^127\.0\.1\.1[[:space:]]' /etc/hosts; then
  sed -ri 's/^127\.0\.1\.1[[:space:]].*/127.0.1.1 ${hostname}/' /etc/hosts
else
  printf '127.0.1.1 %s\n' '${hostname}' >>/etc/hosts
fi

swapoff -a
sed -ri '/[[:space:]]swap[[:space:]]/ { /^[[:space:]]*#/! s/^/# clawmanager-disabled-swap /; }' /etc/fstab
systemctl disable --now ufw 2>/dev/null || true

cat > /etc/modules-load.d/k8s.conf <<'MODULES'
overlay
br_netfilter
MODULES
modprobe overlay
modprobe br_netfilter

cat > /etc/sysctl.d/99-clawmanager-k8s.conf <<'SYSCTL'
net.bridge.bridge-nf-call-iptables = 1
net.bridge.bridge-nf-call-ip6tables = 1
net.ipv4.ip_forward = 1
SYSCTL
sysctl --system >/dev/null

mkdir -p /etc/containerd
# Keep an explicit version 3 CRI configuration for containerd 2.x. The
# version 4 default generated by containerd 2.3 does not expose the CRI gRPC
# service expected by kubeadm in all package configurations.
cat > /etc/containerd/config.toml <<'CONTAINERD'
version = 3
disabled_plugins = []

[plugins.'io.containerd.cri.v1.images']
  snapshotter = 'overlayfs'

  [plugins.'io.containerd.cri.v1.images'.pinned_images]
    sandbox = '${pause_image}'

[plugins.'io.containerd.cri.v1.runtime']
  [plugins.'io.containerd.cri.v1.runtime'.containerd]
    default_runtime_name = 'runc'

    [plugins.'io.containerd.cri.v1.runtime'.containerd.runtimes.runc]
      runtime_type = 'io.containerd.runc.v2'

      [plugins.'io.containerd.cri.v1.runtime'.containerd.runtimes.runc.options]
        SystemdCgroup = true
CONTAINERD

cat > /etc/crictl.yaml <<'CRICTL'
runtime-endpoint: unix:///run/containerd/containerd.sock
image-endpoint: unix:///run/containerd/containerd.sock
timeout: 10
debug: false
CRICTL

systemctl daemon-reload
systemctl enable containerd
systemctl restart containerd
systemctl is-active containerd >/dev/null
ctr plugins ls | grep -Eq '^io\.containerd\.grpc\.v1[[:space:]]+cri[[:space:]].*[[:space:]]ok[[:space:]]*$'
systemctl enable kubelet
systemctl enable --now iscsid 2>/dev/null || systemctl enable --now open-iscsi
systemctl is-active containerd
command -v iscsiadm >/dev/null
command -v mount.nfs >/dev/null
touch '${STATE_DIR}/system_configured'
"
}

stage_image_payload_on_worker() {
  local target=$1
  [[ -f ${IMAGE_ARCHIVE} ]] || die "missing image archive: ${IMAGE_ARCHIVE}"
  [[ -f ${IMAGE_ARCHIVE}.sha256 ]] || die "missing image checksum: ${IMAGE_ARCHIVE}.sha256"

  node_bash "${target}" "mkdir -p '${REMOTE_ROOT}/images'"
  local -a options=()
  mapfile -t options < <(ssh_options)
  local ssh_command
  printf -v ssh_command 'ssh -i %q -p %q -o BatchMode=yes -o ConnectTimeout=10 -o StrictHostKeyChecking=accept-new' \
    "${SSH_PRIVATE_KEY}" "${SSH_PORT}"

  log "syncing the resumable image archive to ${target}"
  rsync -a --partial --info=progress2 \
    -e "${ssh_command}" \
    --rsync-path='sudo -n rsync' \
    "${IMAGE_ARCHIVE}" "${IMAGE_ARCHIVE}.sha256" "${IMAGE_LOCK_FILE}" \
    "${SSH_USER}@${target}:${REMOTE_ROOT}/images/"
}

node_images_are_complete() {
  local target=$1
  node_step_marked "${target}" images_imported || return 1
  local listed image normalized
  listed=$(node_capture "${target}" 'ctr -n k8s.io images list -q') || return 1
  while IFS= read -r image; do
    normalized=$(normalize_image_reference "${image}")
    grep -Fx "${normalized}" <<<"${listed}" >/dev/null || return 1
  done < <(read_image_lock)
}

import_node_images() {
  local target=$1
  local archive lock_file checksum_file
  if [[ ${target} == local ]]; then
    archive=${IMAGE_ARCHIVE}
    lock_file=${IMAGE_LOCK_FILE}
    checksum_file=${IMAGE_ARCHIVE}.sha256
  else
    archive=${REMOTE_ROOT}/images/$(basename "${IMAGE_ARCHIVE}")
    lock_file=${REMOTE_ROOT}/images/$(basename "${IMAGE_LOCK_FILE}")
    checksum_file=${archive}.sha256
  fi

  if node_images_are_complete "${target}"; then
    log "images already imported on ${target}"
    return
  fi

  log "verifying and importing images on ${target}"
  node_bash "${target}" "
set -Eeuo pipefail
archive='${archive}'
lock_file='${lock_file}'
checksum_file='${checksum_file}'
expected=\$(awk '{print \$1}' \"\${checksum_file}\")
actual=\$(sha256sum \"\${archive}\" | awk '{print \$1}')
[[ \"\${actual}\" == \"\${expected}\" ]] || {
  echo 'image archive checksum mismatch' >&2
  exit 46
}
ctr -n k8s.io images import \"\${archive}\"
while IFS='|' read -r key image extra; do
  [[ -z \"\${key}\" || \${key:0:1} == '#' ]] && continue
  [[ -z \"\${extra:-}\" ]] || exit 47
  normalized_image=\"\${image}\"
  image_name=\"\${image%@*}\"
  if [[ \"\${image_name}\" != */* ]]; then
    normalized_image=\"docker.io/library/\${image}\"
  else
    first=\"\${image_name%%/*}\"
    if [[ \"\${first}\" != *.* && \"\${first}\" != *:* && \"\${first}\" != localhost ]]; then
      normalized_image=\"docker.io/\${image}\"
    fi
  fi
  ctr -n k8s.io images list -q | grep -Fx \"\${normalized_image}\" >/dev/null || {
    echo \"imported archive is missing \${image}\" >&2
    exit 48
  }
done <\"\${lock_file}\"
touch '${STATE_DIR}/images_imported'
"
}

detect_control_plane_ip() {
  local cp_index=$1
  local configured=${NODE_IPS[cp_index]}
  if [[ ${configured} != auto ]]; then
    printf '%s' "${configured}"
    return
  fi

  local destination
  if destination="$(first_worker_target 2>/dev/null)"; then
    ip -4 route get "${destination}" | awk '
      /src/ { for (i=1; i<=NF; i++) if ($i == "src") { print $(i+1); exit } }
    '
    return
  fi

  ip -4 route get 1.1.1.1 | awk '
    /src/ { for (i=1; i<=NF; i++) if ($i == "src") { print $(i+1); exit } }
  '
}

detect_worker_ip() {
  local index=$1
  local control_plane_ip=$2
  local configured=${NODE_IPS[index]}
  if [[ ${configured} != auto ]]; then
    printf '%s' "${configured}"
    return
  fi

  node_capture "${NODE_TARGETS[index]}" "ip -4 route get '${control_plane_ip}' | awk '/src/ { for (i=1; i<=NF; i++) if (\$i == \"src\") { print \$(i+1); exit } }'"
}

validate_resolved_node_ips() {
  local -a resolved_ips=("$@")
  local index other ip
  for index in "${!resolved_ips[@]}"; do
    ip=${resolved_ips[index]}
    [[ ${ip} =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]] || die \
      "could not automatically determine node IP for ${NODE_HOSTNAMES[index]}"
    for other in "${!resolved_ips[@]}"; do
      ((other >= index)) && continue
      [[ ${ip} != "${resolved_ips[other]}" ]] || die "duplicate node IP detected: ${ip}"
    done
  done

  RESOLVED_NODE_IPS_CSV="$(IFS=,; printf '%s' "${resolved_ips[*]}")"
  python3 - "${POD_CIDR}" "${SERVICE_CIDR}" "${RESOLVED_NODE_IPS_CSV}" <<'PY'
import ipaddress
import sys

pod = ipaddress.ip_network(sys.argv[1], strict=False)
service = ipaddress.ip_network(sys.argv[2], strict=False)
if pod.overlaps(service):
    raise SystemExit(f"Pod CIDR {pod} overlaps Service CIDR {service}")
for raw in sys.argv[3].split(','):
    address = ipaddress.ip_address(raw)
    if address in pod or address in service:
        raise SystemExit(f"Node IP {address} overlaps a cluster CIDR")
PY
}

write_resolved_nodes() {
  local -a resolved_ips=("$@")
  mkdir -p "${STATE_DIR}"
  : >"${STATE_DIR}/resolved-nodes.conf"
  chmod 600 "${STATE_DIR}/resolved-nodes.conf"
  local index
  for index in "${!NODE_ROLES[@]}"; do
    printf '%s|%s|%s|%s|%s\n' \
      "${NODE_ROLES[index]}" "${NODE_HOSTNAMES[index]}" "${NODE_TARGETS[index]}" \
      "${resolved_ips[index]}" "${NODE_STORAGE[index]}" >>"${STATE_DIR}/resolved-nodes.conf"
  done
}
